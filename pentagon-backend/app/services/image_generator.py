"""High-quality image generation service for Pentagon.

Uses state-of-the-art diffusion models (FLUX.1) via Pollinations AI as the
primary engine for photorealistic, cinematic, and artistic images, with an
offline fallback engine using Pillow and Matplotlib for clean technical diagrams.
"""

from __future__ import annotations

import base64
import io
import logging
import random
import re
import urllib.parse
from pathlib import Path

import httpx
from PIL import Image, ImageDraw

logger = logging.getLogger(__name__)

ASPECT_RATIOS: dict[str, tuple[int, int]] = {
    "16:9": (1280, 720),
    "1:1": (1024, 1024),
    "4:3": (1024, 768),
    "9:16": (720, 1280),
    "wide": (1280, 720),
    "square": (1024, 1024),
}

STYLE_PROMPT_MODIFIERS: dict[str, str] = {
    "photorealistic": (
        "hyperrealistic, 8k resolution, photorealistic, professional photography, studio lighting,"
        " sharp focus, highly detailed, octane render, masterpiece"
    ),
    "cinematic": (
        "cinematic still, 35mm film, dramatic volumetric lighting, anamorphic lens flare,"
        " depth of field, photorealistic, 8k resolution, IMAX quality"
    ),
    "diagram": (
        "clean modern technical architecture diagram, corporate infographic style,"
        " sharp vector graphics, minimalist, clear visual hierarchy, professional presentation illustration"
    ),
    "digital-art": (
        "stunning digital art, trending on artstation, masterpiece, vibrant balanced colors,"
        " intricate details, smooth lighting, concept art"
    ),
    "minimalist": (
        "minimalist modern aesthetic, clean composition, soft shadows, neutral background,"
        " elegant design, high quality"
    ),
}


def enhance_prompt(prompt: str, style: str = "photorealistic") -> str:
    """Enrich the user's prompt with artistic and technical keywords for maximum visual quality."""
    clean_prompt = prompt.strip()
    modifier = STYLE_PROMPT_MODIFIERS.get(style.lower(), STYLE_PROMPT_MODIFIERS["photorealistic"])

    # Avoid duplicate tags if already present in prompt
    words_in_prompt = set(re.findall(r"\w+", clean_prompt.lower()))
    selected_tags = []
    for tag in modifier.split(","):
        tag_words = set(re.findall(r"\w+", tag.lower()))
        if not tag_words.intersection(words_in_prompt):
            selected_tags.append(tag.strip())

    if selected_tags:
        return f"{clean_prompt}, {', '.join(selected_tags[:6])}"
    return clean_prompt


def _generate_fallback_diagram(
    prompt: str, width: int = 1280, height: int = 720
) -> tuple[bytes, str]:
    """Offline high-resolution visual graphic generator using Pillow when external APIs are unreachable."""
    image = Image.new("RGB", (width, height), color=(15, 23, 42))  # Slate 900
    draw = ImageDraw.Draw(image)

    # Gradient background lines
    for y in range(0, height, 4):
        ratio = y / height
        r = int(15 + ratio * 10)
        g = int(23 + ratio * 20)
        b = int(42 + ratio * 35)
        draw.line([(0, y), (width, y)], fill=(r, g, b), width=4)

    # Accent glow card in center
    margin_x = int(width * 0.1)
    margin_y = int(height * 0.15)
    card_rect = [margin_x, margin_y, width - margin_x, height - margin_y]
    draw.rounded_rectangle(card_rect, radius=24, fill=(30, 41, 59), outline=(51, 65, 85), width=2)

    # Header decorative banner
    banner_rect = [margin_x, margin_y, width - margin_x, margin_y + 80]
    draw.rounded_rectangle(banner_rect, radius=24, fill=(16, 185, 129))  # Emerald

    # Draw title
    title_text = "PENTAGON VISUAL WORKSPACE"
    draw.text((margin_x + 30, margin_y + 25), title_text, fill=(0, 0, 0))

    # Draw prompt description
    prompt_lines = [prompt[i : i + 60] for i in range(0, min(len(prompt), 300), 60)]
    cur_y = margin_y + 120
    draw.text((margin_x + 40, cur_y), "Prompt Specification:", fill=(148, 163, 184))
    cur_y += 35
    for line in prompt_lines:
        draw.text((margin_x + 40, cur_y), line, fill=(241, 245, 249))
        cur_y += 30

    # Draw footer watermark
    draw.text((margin_x + 40, height - margin_y - 45), "Generated by Pentagon Engine", fill=(100, 116, 139))

    buf = io.BytesIO()
    image.save(buf, format="JPEG", quality=92)
    return buf.getvalue(), "image/jpeg"


async def generate_image(
    prompt: str,
    style: str = "photorealistic",
    aspect_ratio: str = "16:9",
    seed: int | None = None,
) -> tuple[bytes, str]:
    """Generate a high-quality image from a prompt.

    Returns:
        (image_bytes, mime_type)
    """
    if not prompt or not prompt.strip():
        raise ValueError("Prompt cannot be empty.")

    width, height = ASPECT_RATIOS.get(aspect_ratio.lower(), (1280, 720))
    enhanced = enhance_prompt(prompt, style=style)
    encoded_prompt = urllib.parse.quote(enhanced)
    actual_seed = seed if seed is not None else random.randint(1, 9999999)

    # Primary generator: FLUX.1 model via Pollinations
    url = (
        f"https://image.pollinations.ai/prompt/{encoded_prompt}"
        f"?width={width}&height={height}&model=flux&nologo=true&seed={actual_seed}"
    )

    try:
        async with httpx.AsyncClient(timeout=12.0, follow_redirects=True) as client:
            response = await client.get(url, headers={"User-Agent": "PentagonAI/2.0"})
            if response.status_code == 200 and len(response.content) > 1000:
                # Validate image header with PIL
                img = Image.open(io.BytesIO(response.content))
                img.verify()
                content_type = "image/jpeg" if img.format == "JPEG" else "image/png"
                return response.content, content_type
    except Exception as exc:
        logger.warning("Primary image generation failed (%s), using fallback: %s", url[:60], exc)

    # Fallback to local vector generator
    return _generate_fallback_diagram(prompt, width=width, height=height)


def resolve_image_bytes(source: str) -> tuple[bytes, str] | None:
    """Resolve an image reference (data URI, HTTP URL, generate directive, or local file) into raw bytes.

    Can be called synchronously inside document builder workers.
    """
    if not source:
        return None

    source = source.strip()

    # Case 1: Data URI
    if source.startswith("data:image/"):
        try:
            header, encoded = source.split(",", 1)
            mime = header.split(";")[0].replace("data:", "")
            return base64.b64decode(encoded), mime
        except Exception:
            return None

    # Case 2: On-the-fly generation directive: generate:prompt or generate_image:prompt
    if source.lower().startswith(("generate:", "generate_image:")):
        prompt = source.split(":", 1)[1].strip()
        enhanced = enhance_prompt(prompt, style="photorealistic")
        encoded = urllib.parse.quote(enhanced)
        url = f"https://image.pollinations.ai/prompt/{encoded}?width=1024&height=576&model=flux&nologo=true"
        try:
            with httpx.Client(timeout=25.0, follow_redirects=True) as client:
                res = client.get(url, headers={"User-Agent": "PentagonAI/2.0"})
                if res.status_code == 200 and len(res.content) > 1000:
                    return res.content, "image/jpeg"
        except Exception:
            return _generate_fallback_diagram(prompt, width=1024, height=576)

    # Case 3: Remote HTTP / HTTPS URL
    if source.startswith(("http://", "https://")):
        try:
            with httpx.Client(timeout=20.0, follow_redirects=True) as client:
                res = client.get(
                    source,
                    headers={
                        "User-Agent": (
                            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                            "AppleWebKit/537.36 (KHTML, like Gecko) "
                            "Chrome/124.0.0.0 Safari/537.36"
                        )
                    },
                )
                if res.status_code == 200 and len(res.content) > 500:
                    raw = res.content
                    try:
                        pil_img = Image.open(io.BytesIO(raw))
                        fmt = pil_img.format or "JPEG"
                        # Normalize format to JPEG or PNG for universal document rendering
                        if fmt not in ("JPEG", "PNG"):
                            rgb_img = pil_img.convert("RGB")
                            out_buf = io.BytesIO()
                            rgb_img.save(out_buf, format="JPEG", quality=92)
                            return out_buf.getvalue(), "image/jpeg"
                        content_type = "image/png" if fmt == "PNG" else "image/jpeg"
                        return raw, content_type
                    except Exception:
                        content_type = (res.headers.get("content-type") or "image/jpeg").split(";")[0].strip()
                        return raw, content_type
        except Exception as exc:
            logger.debug("Failed to fetch remote image %s: %s", source[:60], exc)
            return None

    # Case 4: File ID or /api/files/ URL
    uuid_match = re.search(r"([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})", source)
    if uuid_match:
        fid = uuid_match.group(1)
        try:
            from app.db.session import SessionLocal
            from app.db.models import GeneratedFile
            from app.config import settings
            with SessionLocal() as db:
                row = db.query(GeneratedFile).filter(GeneratedFile.id == fid).first()
                if row and row.storage_path:
                    local_p = settings.generated_file_directory / row.storage_path
                    if local_p.exists():
                        return local_p.read_bytes(), row.media_type or "image/jpeg"
        except Exception as exc:
            logger.debug("Could not resolve file ID %s directly: %s", fid, exc)

    # Case 5: Local path or storage reference
    path = Path(source)
    if path.exists() and path.is_file():
        try:
            data = path.read_bytes()
            return data, "image/jpeg"
        except Exception:
            return None

    return None

